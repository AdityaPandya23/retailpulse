"""Deploy helper: the .gitignore block that tracks exactly the app inputs (contracts.APP_FILES).

data/ and artifacts/* stay ignored; each app directory is re-included, its contents ignored
again, then only the named app files are re-included (so features_full.parquet, raw/processed
parquet and *.tmp files can never be committed by accident).

Rewrite the block after APP_FILES changes:  python -m retailpulse.deploy
"""

from __future__ import annotations

from pathlib import Path

from retailpulse import contracts as C
from retailpulse.config import ROOT

GITIGNORE = ROOT / ".gitignore"
BEGIN = "# >>> app artifacts (generated by `python -m retailpulse.deploy`; do not edit) >>>"
END = "# <<< app artifacts <<<"


def app_paths() -> list[str]:
    """APP_FILES as repo-relative POSIX paths, sorted."""
    return sorted(Path(p).relative_to(ROOT).as_posix() for p in C.APP_FILES)


def gitignore_lines() -> list[str]:
    """Re-include lines for every app file (dirs opened, then closed to everything else)."""
    lines: list[str] = []
    done_dirs: set[str] = set()
    for rel in app_paths():
        parent = rel.rsplit("/", 1)[0]
        if parent != "artifacts" and parent not in done_dirs:
            lines += [f"!{parent}/", f"{parent}/*"]
            done_dirs.add(parent)
        lines.append(f"!{rel}")
    return lines


def render_block() -> str:
    return "\n".join([BEGIN, *gitignore_lines(), END])


def update_gitignore(path: Path = GITIGNORE) -> bool:
    """Replace (or append) the generated block; True if the file changed."""
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    block = render_block()
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
        new = head + block + tail
    else:
        new = text.rstrip("\n") + "\n\n" + block + "\n"
    if new == text:
        return False
    path.write_text(new, encoding="utf-8")
    return True


if __name__ == "__main__":
    changed = update_gitignore()
    print(
        f"{GITIGNORE.name}: {'updated' if changed else 'already up to date'} "
        f"({len(app_paths())} app files)"
    )
